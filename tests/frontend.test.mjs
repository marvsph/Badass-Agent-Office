import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

test('office boots, draws real session data, filters projects, and opens agent details',async()=>{
  const pageIDs=new Set([...fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8').matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]));
  const listeners=new Map(),elements=new Map(),storage=new Map();
  const drawing=new Proxy({measureText:text=>({width:String(text).length*5}),createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})},{get:(obj,key)=>key in obj?obj[key]:(()=>{}),set:(obj,key,value)=>(obj[key]=value,true)});
  const element=id=>{
    assert.ok(pageIDs.has(id),`the actual page contains #${id}`);
    if(!elements.has(id))elements.set(id,{id,hidden:false,value:'',style:{},innerHTML:'',textContent:'',classList:{toggle(){},add(){},remove(){}},getContext:()=>drawing,getBoundingClientRect:()=>({width:1100,height:455,left:0,top:0}),addEventListener:(name,cb)=>listeners.set(`${id}:${name}`,cb),setAttribute(){},setPointerCapture(){},focus(){},showModal(){},close(){}});
    return elements.get(id);
  };
  let sessions=[
    {id:'one',name:'Codex',title:'Website edits',project:'Website',projectPath:'C:/Website',parentId:null,role:'Project session',model:'Reported model',lastSeen:Date.now(),updatedAt:Date.now(),status:'working',activity:'Editing files',kind:'coding',tokens:123,colorIndex:0,activityLog:[{label:'Editing files',kind:'coding',timestamp:Date.now()}]},
    {id:'two',name:'Reviewer',title:'Review',project:'Second',projectPath:'C:/Second',parentId:'one',role:'Subagent',model:'Reported model',lastSeen:Date.now(),updatedAt:Date.now(),status:'idle',activity:'Turn finished',kind:'done',tokens:null,colorIndex:1,activityLog:[]}
  ];
  const world={connected:true,observedAt:Date.now(),sessions,projects:[{name:'Website',path:'C:/Website',count:1},{name:'Second',path:'C:/Second',count:1}]};
  let observationNow=Date.now();
  class ObservationDate extends Date{static now(){return observationNow;}}
  let nextFrame;
  const context=vm.createContext({console,Intl,Date:ObservationDate,Math,String,Number,Map,Set,JSON,AbortSignal,Image:class{constructor(){this.naturalWidth=1254;this.naturalHeight=1254;}},devicePixelRatio:1,localStorage:{getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)},window:{matchMedia:()=>({matches:false})},document:{getElementById:element,querySelectorAll:()=>[],addEventListener(){},body:{classList:{toggle(){}}}},ResizeObserver:class{constructor(cb){this.cb=cb;}observe(){this.cb();}},fetch:async()=>({ok:true,json:async()=>world}),setInterval:()=>0,requestAnimationFrame:cb=>{nextFrame=cb;}});
  for(const name of ['boss-report.js','session-visibility.js','floor-attention.js','worker-names.js','worker-profile.js','worker-animation.js','worker-activity-renderer.js','worker-activity-frames.js','office-scene.js','boss-animation.js','building-scene.js','office-settings.js','office-tasks.js','app.js']){
    const source=fs.readFileSync(new URL('../public/'+name,import.meta.url),'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
    vm.runInContext(source,context);
  }
  await new Promise(resolve=>setImmediate(resolve));
  sessions=world.sessions;
  nextFrame(500);
  assert.equal(element('stat-team').textContent,2);
  assert.equal(element('stat-working').textContent,1);
  assert.equal(vm.runInContext('officeScene.floors.size',context),2);
  assert.equal(vm.runInContext('officeScene.report.totals.workers',context),2);
  assert.ok(vm.runInContext('officeScene.bossHit !== null',context),'central Boss room is clickable');
  assert.match(element('boss-project-reports').innerHTML,/Website/);
  assert.match(element('boss-project-reports').innerHTML,/Second/);
  assert.doesNotMatch(element('boss-attention').innerHTML,/\$\{/,'attention counts are rendered values');
  assert.equal(element('boss-report').hidden,false,'desktop reports start beside the canvas');
  listeners.get('toggle-reports:click')();
  assert.equal(element('boss-report').hidden,true,'toggle hides the report');
  assert.equal(element('toggle-reports').textContent,'Show reports');
  listeners.get('toggle-reports:click')();
  assert.equal(element('boss-report').hidden,false,'toggle reopens the report');
  listeners.get('boss-sidebar-close:click')();
  assert.equal(element('boss-report').hidden,true,'sidebar close hides the report');
  listeners.get('project:change')({target:{value:'C:/Website'}});
  for(let frame=0;frame<90;frame++)nextFrame(1000+frame*16.667);
  assert.ok(vm.runInContext('hits.some(h=>h.id==="one")',context),'project navigation brings real workers into view');
  const libraryPointer=vm.runInContext('(()=>{const floor=officeScene.floors.get("C:/Website"),room=floor.rooms.find(room=>room.id==="library");return{x:officeScene.offset.x+pan.x+(floor.origin.x+room.x+room.w/2)*officeScene.scale,y:officeScene.offset.y+pan.y+(floor.origin.y+room.y+room.h/2)*officeScene.scale};})()',context);
  listeners.get('office:pointermove')({clientX:libraryPointer.x,clientY:libraryPointer.y});
  assert.equal(element('room-hover').hidden,false,'hover reveals the room description pill');
  assert.equal(element('room-hover-name').textContent,'LIBRARY');
  assert.equal(element('room-hover-purpose').textContent,'Research & reading');
  vm.runInContext('pan={x:5000,y:0}',context);nextFrame(2600);
  assert.equal(element('room-hover').hidden,true,'camera movement refreshes the pill even without a new pointer event');
  vm.runInContext('pan={x:0,y:0}',context);nextFrame(2650);
  assert.equal(element('room-hover').hidden,false);
  listeners.get('office:pointerdown')({clientX:libraryPointer.x,clientY:libraryPointer.y,pointerId:1});
  assert.equal(element('room-hover').hidden,true,'dragging dismisses hover descriptions');
  listeners.get('office:pointercancel')();
  listeners.get('office:pointermove')({clientX:libraryPointer.x,clientY:libraryPointer.y});
  listeners.get('office:pointerleave')();
  assert.equal(element('room-hover').hidden,true,'leaving the canvas clears the description');
  vm.runInContext('showRoomDetail("C:/Website","studio")',context);
  assert.match(element('detail-content').innerHTML,/Plans &amp; task design/);
  assert.match(element('detail-content').innerHTML,/No workers here right now/);
  vm.runInContext('updateInterface()',context);
  assert.match(element('detail-content').innerHTML,/Planning studio/,'room inspection survives observation refreshes');
  listeners.get('close-detail:click')();
  assert.equal(element('stat-team').textContent,1);
  assert.equal(vm.runInContext('officeScene.floors.size',context),2,'other project floors remain in the continuous building');
  vm.runInContext("showDetail('one');setTheme('night');",context);
  assert.equal(element('detail').hidden,false);
  assert.match(element('detail-content').innerHTML,/Website edits/);
  const profileHTML=element('detail-content').innerHTML;
  assert.match(profileHTML,/<div class="detail-portrait"><span class="pixel-profile" role="img"/,'selected worker uses its pixel sprite');
  assert.match(profileHTML,/Recorded activity includes file edits\./);
  assert.ok(profileHTML.indexOf('status-chip')<profileHTML.indexOf('work-summary')&&profileHTML.indexOf('work-summary')<profileHTML.indexOf('detail-data'),'recorded work sits between status and metadata');
  assert.match(element('detail-content').innerHTML,/Recorded name/,'office aliases preserve the original name in the inspector');
  assert.equal(vm.runInContext('state.theme',context),'night');
  nextFrame(1500);
  vm.runInContext("showDetail('two');",context);
  assert.equal(vm.runInContext('state.project',context),'C:/Second');
  listeners.get('boss-focus:click')();
  assert.equal(element('boss-report').hidden,false,'Boss room navigation reopens the sidebar');
  assert.equal(vm.runInContext('state.project',context),'');
  assert.equal(element('stat-team').textContent,2);
  assert.equal(element('detail').hidden,true);
  assert.equal(vm.runInContext('officeScene.floors.size',context),2,'Boss navigation retains existing floors');

  const oldTime=Date.now()-7*60*60*1000;
  const archived={...sessions[0],id:'archived',name:'Archived worker',lastSeen:oldTime,updatedAt:oldTime};
  world.sessions.push(archived);
  vm.runInContext('updateInterface()',context);
  vm.runInContext('setProjects(state.world.projects)',context);
  assert.match(element('project').innerHTML,/Website \(1\)/,'project selector counts current floor workers');
  assert.equal(element('boss-nav-count').textContent,2,'Boss navigation counts visible workers');
  assert.equal(element('stat-team').textContent,2,'older sessions do not add floor workers');
  assert.equal(vm.runInContext('officeScene.report.totals.workers',context),3,'older records remain in reports');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("archived")',context),false);
  assert.doesNotMatch(element('team').innerHTML,/Archived worker/);
  listeners.get('show-history:change')({target:{checked:true}});
  assert.match(element('team').innerHTML,/Archived worker/,'older records remain inspectable');
  assert.equal(element('stat-team').textContent,2,'history does not bypass the six-hour floor limit');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("archived")',context),false);
  vm.runInContext('showDetail("archived")',context);
  assert.match(element('detail-content').innerHTML,/Not on the floor/,'archived sessions are not shown as arriving workers');
  archived.lastSeen=Date.now();
  vm.runInContext('updateInterface()',context);
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("archived")',context),true,'a new activity record returns the worker');
  archived.lastSeen=oldTime;
  vm.runInContext('updateInterface()',context);
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("archived")',context),false,'refresh removes a worker after expiry');

  const planner={...sessions[0],id:'planner',name:'Planner',kind:'planning',activity:'Planning',activityLog:[{label:'Planning',kind:'planning',timestamp:Date.now()}]};
  world.sessions.push(planner);sessions[0].parentId='planner';
  vm.runInContext("closeDetail();state.project='';updateInterface()",context);
  assert.equal(element('stat-team').textContent,3,'planning sessions keep their floor workers');
  assert.equal(element('stat-working').textContent,2,'planning counts as active work');
  assert.match(element('team').innerHTML,/Planner/);
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workerConnections().length',context),1);
  vm.runInContext('showDetail("planner")',context);
  assert.match(element('detail-content').innerHTML,/>Planning</,'planning is explicit in worker details');
  planner.lastSeen=oldTime;planner.updatedAt=oldTime;
  vm.runInContext('updateInterface()',context);
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("planner")',context),false,'planning does not bypass the six-hour limit');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workerConnections().length',context),0,'expired planner connections disappear');

  observationNow=Date.now()+1000;
  sessions[0].status='idle';sessions[0].kind='done';sessions[0].activity='Turn finished';
  sessions[0].activityLog=[{kind:'done',label:'Turn finished',timestamp:observationNow-1}];
  sessions[1].status='working';sessions[1].lastSeen=observationNow;
  world.sessions.push({...sessions[0],id:'other-completion',name:'Another worker',parentId:null,activityLog:[{kind:'done',label:'Turn finished',timestamp:observationNow-2}]});
  world.sessions.push({...sessions[0],id:'spawned-completion',name:'Spawned worker',parentId:'one',activityLog:[{kind:'done',label:'Turn finished',timestamp:observationNow-3}]});
  world.sessions.push({...sessions[0],id:'nested-completion',name:'Nested worker',parentId:'spawned-completion',activityLog:[{kind:'done',label:'Turn finished',timestamp:observationNow-4}]});
  vm.runInContext("closeDetail();state.project='';updateInterface()",context);
  assert.match(element('building-floors').innerHTML,/floor-attention/,'finished floor gets an attention badge');
  assert.ok(element('building-floors').innerHTML.indexOf('C:/Website')<element('building-floors').innerHTML.indexOf('C:/Second'),'unviewed completion sorts before an active floor');
  assert.match(element('project').innerHTML,/! Website/,'selector uses the same attention state');
  assert.match(element('team').innerHTML,/worker-attention/,'finished workers are marked in the sidebar');
  assert.ok(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("one").agent.unreadCompletionAt>0',context),'the canvas receives the unread completion marker');
  assert.ok(storage.has('ao-floor-attention'),'attention state stays in local browser storage');
  vm.runInContext("floorAttention=JSON.parse(localStorage.getItem('ao-floor-attention'));state.project='C:/Website';document.visibilityState='hidden';updateInterface()",context);
  assert.match(element('building-floors').innerHTML,/floor-attention/,'a selected floor in a hidden tab is not viewed');
  listeners.get('building-floors:click')({target:{closest:selector=>selector==='[data-floor]'?{dataset:{floor:'C:/Website'}}:null}});
  vm.runInContext("document.visibilityState='visible';updateInterface()",context);
  assert.match(element('building-floors').innerHTML,/floor-attention/,'opening a floor keeps worker updates available to inspect');
  vm.runInContext('showDetail("one")',context);
  assert.match(element('detail-content').innerHTML,/Turn finished/,'inspecting a marker opens recorded activity');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("one").agent.unreadCompletionAt',context),0,'inspected worker marker clears');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("spawned-completion").agent.unreadCompletionAt',context),0,'opening the main worker clears its child marker immediately');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("nested-completion").agent.unreadCompletionAt',context),0,'nested subagent markers clear too');
  assert.ok(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("other-completion").agent.unreadCompletionAt>0',context),'another worker on that floor stays unread');
  listeners.get('project:change')({target:{value:'C:/Second'}});
  let stopped=false;
  listeners.get('building-floors:click')({stopPropagation(){stopped=true;},target:{closest:selector=>selector==='[data-read-floor]'?{dataset:{readFloor:'C:/Website'}}:null}});
  assert.equal(stopped,true,'the attention button does not trigger floor navigation');
  assert.equal(vm.runInContext('state.project',context),'C:/Second','marking a different floor read does not move the camera');
  assert.doesNotMatch(element('building-floors').innerHTML,/floor-attention/,'floor attention button clears all its worker updates');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.get("other-completion").agent.unreadCompletionAt',context),0,'bulk read immediately clears canvas markers');
  vm.runInContext("state.project='';updateInterface()",context);
  assert.doesNotMatch(element('building-floors').innerHTML,/floor-attention/,'later polls do not restore viewed completions');
  assert.ok(element('building-floors').innerHTML.indexOf('C:/Second')<element('building-floors').innerHTML.indexOf('C:/Website'),'normal activity sorting resumes');
  world.sessions=Array.from({length:1000},(_,i)=>({...sessions[0],id:'crowd-'+i,parentId:'crowd-lead',status:'working',kind:'coding',lastSeen:observationNow,updatedAt:observationNow,activityLog:[]}));
  world.sessions.push({...world.sessions[0],id:'crowd-lead',name:'Crowd lead',parentId:null});
  vm.runInContext('closeDetail();updateInterface()',context);
  assert.equal(element('stat-team').textContent,24,'room limits bound floor sprites for 1000 subagents');
  assert.equal(element('team-count').textContent,1001,'hidden subagents keep their inspectable session records');
  assert.match(element('floor-subtitle').textContent,/977 off floor/);
  vm.runInContext('showDetail("crowd-999")',context);
  assert.match(element('detail-content').innerHTML,/Off floor: room limit/,'hidden records are not described as arriving');
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("crowd-999")',context),false);
  world.sessions.push({...world.sessions[0],id:'new-main',name:'New main session',parentId:null,lastSeen:observationNow+1});
  vm.runInContext('closeDetail();updateInterface()',context);
  assert.equal(vm.runInContext('officeScene.floors.get("C:/Website").workers.has("new-main")',context),true,'new main session takes a subagent slot');
  assert.equal(element('stat-team').textContent,24);
  world.connected=false;world.sessions=[];world.projects=[];world.csrfToken='setup-token';world.office={name:'New Studio',logoUrl:null};
  await vm.runInContext('fetchWorld()',context);
  assert.equal(element('brand-name').textContent,'New Studio');
  assert.equal(element('setup-state').hidden,false,'new installations show setup without provider records');
  assert.equal(vm.runInContext('state.world.csrfToken',context),'setup-token','disconnected providers still permit local configuration');
  assert.ok(listeners.has('configure:click'));
  world.projects=[{name:'New Floor',path:'C:/NewFloor',count:0}];
  await vm.runInContext('fetchWorld()',context);
  assert.equal(element('setup-state').hidden,true);
  assert.equal(vm.runInContext('officeScene.floors.has("C:/NewFloor")',context),true,'configured floors appear without sessions');
  assert.equal(vm.runInContext('officeScene.floors.has("C:/Website")',context),false,'removed floors leave the canvas');
});
